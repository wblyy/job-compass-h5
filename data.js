/**
 * 公众号 / 网页双通道 3C 真人模拟面试点评生成器（引用用户真实作答，绝不空泛夸奖）
 */
function evaluateMockAnswer(userAnswer) {
  const clean = String(userAnswer || '').trim();
  const hasAdmit = /没做过|没有|空白|确实没|不熟|缺/.test(clean);
  const hasNumber = /31|14|6|7|96%|三套|七个/.test(clean);
  const snippet = clean.length > 26 ? clean.slice(0, 26) + '…' : clean;

  const strengths = [];
  const gaps = [];
  if (hasAdmit) strengths.push('开头坦然认下行业空白，没有硬拗概念，HR 听感诚实');
  else gaps.push('未正面回应「没做过医疗」的顾虑，容易被面试官判定在绕弯子');

  if (hasNumber) strengths.push('给出了原稿里的真实量化锚点（31 节点 / 14→6 天 / 7 部门），说服力扎实');
  else gaps.push('缺少具体量化锚点，建议把原稿里的「31 个节点、14 天压到 6 天」带出来');

  if (!/[?？]|请问|更卡|更看重|哪一块/.test(clean)) {
    gaps.push('结尾停在自证，没把话题交回给业务方确认他们的真实卡点');
  }

  return {
    quoted: `你刚才答的是：「${snippet}」`,
    verdict: strengths.length >= 2 ? '结构稳，可直接上场（差最后一句反问收尾）' : '方向对，但还得补一处硬锚点',
    strengths: strengths.length ? strengths : ['语态自然，没有背诵网传模板的痕迹'],
    gaps: gaps.length ? gaps : ['节奏已经很稳，注意现场语速放慢，留出对方追问空间'],
    upgrade: '建议替换说法：「医疗 HIS 单据我确实没直接摸过，前两周需要跟实施补业务课；但你们卡的跨科室流转推诿，和我把 7 个部门、31 个线下节点收口成工单系统（交付 14→6 天）是同一类状态机问题。你们目前更缺懂临床规则的人，还是能把复杂流程落成系统的人？」'
  };
}

